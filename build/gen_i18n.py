"""Generate app/static/i18n.js from src/i18n-core.js and build/translations.py."""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from translations import PATTERNS, PL, TR  # noqa: E402

core = open("src/i18n-core.js", encoding="utf-8").read()
norm = lambda s: " ".join(s.split())
tr = {norm(k): list(v) for k, v in TR.items()}
pl = {k: [list(v[0]), list(v[1])] for k, v in PL.items()}
pats = ",\n  ".join(f"[/{p}/, {json.dumps(en, ensure_ascii=False)}, {json.dumps(de, ensure_ascii=False)}]" for p, en, de in PATTERNS)
out = ("/* Generated by build/gen_i18n.py – edit build/translations.py and src/i18n-core.js instead. */\n"
       f"window.I18N_TR = {json.dumps(tr, ensure_ascii=False, indent=0)};\n"
       f"window.I18N_PL = {json.dumps(pl, ensure_ascii=False)};\n"
       f"window.I18N_PATTERNS = [\n  {pats}\n];\n" + core)
open("app/static/i18n.js", "w", encoding="utf-8").write(out)
print("i18n.js:", len(tr), "texts,", len(pl), "plurals,", len(PATTERNS), "patterns")
